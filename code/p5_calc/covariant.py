#!/usr/bin/env python3
"""XVI-P p16: COVARIANT evaluation route for one-loop two-point graphs under the frozen p14r DRED prescription.

Why (p16 finding C1).  The p14r R3 component lifting (dred.lift_reduce_monomial) reduces each exported COMPONENT
monomial l_{r1}..l_{rn} separately, AFTER the internal index sums of the exported numerator were done in components.
For rank >= 4 numerators (D01, D03) this produces Gt-QUADRATIC component sums such as sum_rs eta^rr eta^ss Gt_rs Gt_rs,
whose abstract value (tr gtilde.gtilde = tr gtilde = 4 - d, gtilde.gtilde = gtilde) cannot be recovered from the
summed component polynomial: a fixed 4-component basis of Q4S cannot carry a projector of non-integer trace (Siegel's
DRED consistency issue), and the linear realization Gt = (4-d) M (integrals.realization) is faithful only for
expressions LINEAR in Gt.  dred.eta_trace_Gt refuses such patterns (UncontractedObjects).  D13 (rank 3) is linear in
Gt and unaffected.

The covariant route evaluates the SAME rules R1-R6 without any component basis inside the loop:
  C1  the exported 4D component numerator N_A(l, p) (frozen, sha-pinned) is written EXACTLY as a covariant polynomial
      sum_j c_j B_j(eta, l, p) with free external indices only (all internal contractions appear as the scalars l.l,
      l.p, p.p); exactness is VERIFIED as a polynomial identity on every exported component.  Uniqueness: with at most
      8 vector slots no 4D dimension-dependent (Schouten/Gram) identity exists among the B_j (needs >= 10 slots).
  C2  R3 lift: eta -> g4 on the free external indices; l, p in QdS (R2).
  C3a Feynman-parameter route: l = k + x p, symmetric integration in QdS over free indices only
      (k_a k_b -> ghat_ab k^2/d, k.p -> p), x-integrals exact (integrals.fp_ratio)  -- no S0, no Gram.
  C3b Passarino-Veltman route: frozen dred.reduce_tensor (Gram projection in ghat, abstract indices) on the free
      l-indices, scalar J[a,b] from the certified library (S0 for cancelled propagators).
  C4  external 4D projection (R4/R5): ghat_ab = g4_ab - gt_ab on FREE indices (no trace arises); products gt_ab gt_cd
      with distinct free indices are genuine evanescent tensors (kept, R6).
  C5  Laurent / MS-bar with d symbolic (opaque d; dred.substitute_d only).
Output: {canonical structure: A(d)} with Ghat = sum_s A_s(d) * s * MB.
"""
from __future__ import annotations
