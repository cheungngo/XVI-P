import dred  # noqa: E402
import integrals as IL  # noqa: E402

d = dred.d
ETA = dred.ETA
HC = [(0, 0), (0, 1), (0, 2), (0, 3), (1, 1), (1, 2), (1, 3), (2, 2), (2, 3), (3, 3)]
LL, LP, PP = sp.Symbol("l.l"), sp.Symbol("l.p"), IL.PP
MB = IL.MB


# ------------------------------------------------------------------------------------------------ structures
# a factor is ('g4', a, b) | ('gt', a, b) | ('gh', a, b) | ('l', a) | ('p', a)   (a, b external index labels)
def canon(facs):
    out = []
    for f in facs:
        if f[0] in ("g4", "gt", "gh"):
            a, b = sorted(f[1:])
            out.append((f[0], a, b))
        else:
            out.append(f)
    return tuple(sorted(out))


def relabel(facs, perm):
    return canon([(f[0],) + tuple(perm.get(x, x) for x in f[1:]) for f in facs])


def orbit(facs, group):
    return frozenset(relabel(facs, g) for g in group)


def sym_group(pairs):
    """the symmetry group generated by swapping the members of each symmetric external pair."""
    gens = [dict(zip(p, p[::-1])) for p in pairs]
    group = []
    for bits in itertools.product((0, 1), repeat=len(gens)):
        g = {}
        for b, gen in zip(bits, gens):
            if b:
                g.update(gen)
        group.append(g)
    return group


def _matchings(items):
    if not items:
        yield []
        return
    a = items[0]
    for k in range(1, len(items)):
        rest = items[1:k] + items[k + 1:]
        for m in _matchings(rest):
            yield [(a, items[k])] + m


def numerator_ansatz(labels, degree, pairs):
    """all covariant monomials in g4 (external pairs), l_a, p_a and scalars l.l, l.p, p.p of total momentum degree
    `degree`, symmetrised over the symmetric external pairs -> list of (orbit, scalar)."""
    group = sym_group(pairs)
    seen, out = set(), []
    n = len(labels)
    for k in range(n // 2 + 1):
        for sub in itertools.combinations(labels, 2 * k):
            for m in _matchings(list(sub)):
                rest = [x for x in labels if x not in sub]
                for lp in itertools.product(("l", "p"), repeat=len(rest)):
                    R = degree - len(rest)
                    if R < 0 or R % 2:
                        continue
                    facs = canon([("g4", a, b) for a, b in m] + [(t, x) for t, x in zip(lp, rest)])
                    orb = orbit(facs, group)
                    for a_ in range(R // 2 + 1):
                        for b_ in range(R // 2 + 1 - a_):
                            c_ = R // 2 - a_ - b_
                            sc = LL ** a_ * LP ** b_ * PP ** c_
                            key = (orb, sc)
                            if key not in seen:
                                seen.add(key)
                                out.append(key)
    return out


# ------------------------------------------------------------------------------------------------ component evaluation
def _comp_value(facs, assign, lsym, psym):
    v = sp.Integer(1)
    for f in facs:
        if f[0] == "g4":
            a, b = assign[f[1]], assign[f[2]]
            v *= ETA[a] if a == b else 0
        elif f[0] == "l":
            v *= lsym[assign[f[1]]]
        elif f[0] == "p":
            v *= psym[assign[f[1]]]
        else:
            raise ValueError(f)
        if v == 0:
            return v
    return v


def orbit_value(orb, assign, lsym, psym):
    return sp.Add(*[_comp_value(f, assign, lsym, psym) for f in orb])


def scalars(lsym, psym):
    return {LL: sum(ETA[r] * lsym[r] ** 2 for r in range(4)), LP: sum(ETA[r] * lsym[r] * psym[r] for r in range(4)),
            PP: sum(ETA[r] * psym[r] ** 2 for r in range(4))}


def assignments(spec):
    """spec: list of ('pair', (a, b)) | ('vec', a) external legs in export order -> list of (comp key, {label: idx})."""
    per = []
    for kind, lab in spec:
        if kind == "pair":
            per.append([(i, {lab[0]: m, lab[1]: n}) for i, (m, n) in enumerate(HC)])
        else:
            per.append([(i, {lab: i}) for i in range(4)])
    out = []
    for combo in itertools.product(*per):
        key = ",".join(str(c[0]) for c in combo)
        asg = {}
        for c in combo:
            asg.update(c[1])
        out.append((key, asg))
    return out


def export_poly(rows, lsym, psym):
    tot = 0
    for names, cf in rows:
        m = sp.Rational(cf)
        for v in names:
            m *= lsym[int(v[1])] if v[0] == "l" else psym[int(v[1])]
        tot += m
    return sp.expand(tot)


def pair_weight(spec, asg, offdiag, upper=False):
    """off-diagonal component weight per symmetric pair (offdiag: number or tuple, one entry per pair)."""
    w = sp.Integer(1)
    pairs = [lab for kind, lab in spec if kind == "pair"]
    ws = offdiag if isinstance(offdiag, (tuple, list)) else [offdiag] * len(pairs)
    for lab, wo in zip(pairs, ws):
        if asg[lab[0]] != asg[lab[1]]:
            w *= wo
    if upper:                       # coefficient tensor with UPPER external indices (dual to lower field components)
        for x, i in asg.items():
            w *= ETA[i]
    return w


def covariant_fit(numerator, spec, degree, seeds=tuple(range(1, 13)), offdiag=1, upper=False, polys=None):
    """C1: exact covariant form of the exported component numerator (or of given component polynomials `polys` in
    l0..l3, p0..p3); verified as a polynomial identity on every component."""
    labels = [x for kind, lab in spec for x in (lab if kind == "pair" else (lab,))]
    pairs = [lab for kind, lab in spec if kind == "pair"]
    ansatz = numerator_ansatz(labels, degree, pairs)
    asg = assignments(spec)
    ls, ps = sp.symbols("l0:4"), sp.symbols("p0:4")
    rows, rhs = [], []
    if polys is None:
        polys = {k: export_poly(numerator.get(k, []), ls, ps) for k, _ in asg}
    else:
        polys = {k: sp.expand(polys.get(k, 0)) for k, _ in asg}
    for sd in seeds:
        rnd = random.Random(sd)
        lv = [sp.Rational(rnd.randint(-9, 9), rnd.randint(1, 4)) for _ in range(4)]
        pv = [sp.Rational(rnd.randint(-9, 9), rnd.randint(1, 4)) for _ in range(4)]
        sub = dict(zip(ls, lv)) | dict(zip(ps, pv))
        scn = scalars(lv, pv)
        for k, a in asg:
            w = pair_weight(spec, a, offdiag, upper)
            rows.append([w * orbit_value(orb, a, lv, pv) * sc.xreplace(scn) for orb, sc in ansatz])
            rhs.append(polys[k].xreplace(sub))
    from sympy.polys.matrices import DomainMatrix
    n = len(ansatz)
    Aug = DomainMatrix([[sp.QQ.convert(sp.Rational(x)) for x in r] + [sp.QQ.convert(sp.Rational(y))]
                        for r, y in zip(rows, rhs)], (len(rows), n + 1), sp.QQ)
    R, piv = Aug.rref()
    cols = [p for p in piv if p < n]
    if n in piv:
        return {"terms": [], "n_ansatz": n, "n_used": 0, "exact": False, "bad_components": ["inconsistent"],
                "rank": len(cols), "unique": False}
    Rl = R.to_Matrix()
    coef = {}
    for i, j in enumerate(cols):
        c = sp.Rational(Rl[i, n])
        if c != 0:
            coef[j] = c
    # exact verification as polynomial identity on every component
    scs = scalars(ls, ps)
    bad = []
    for k, a in asg:
        e = pair_weight(spec, a, offdiag, upper) * sum(c * orbit_value(ansatz[j][0], a, ls, ps) * ansatz[j][1].xreplace(scs)
                                                for j, c in coef.items())
        if sp.expand(e - polys[k]) != 0:
            bad.append(k)
    terms = [(ansatz[j][0], ansatz[j][1], c) for j, c in coef.items()]
    return {"terms": terms, "n_ansatz": len(ansatz), "n_used": len(terms), "exact": not bad,
            "bad_components": bad[:5], "rank": len(cols), "unique": len(cols) == len(ansatz), "offdiag_weight": str(offdiag), "upper": upper}


# ------------------------------------------------------------------------------------------------ C3a Feynman parameters
_X = sp.Symbol("x")
_K2, _KP = sp.Symbol("k.k"), sp.Symbol("k.p")


def _sym_pairings(items):
    """symmetric integration of k_{items} (labels or 'P' for k.p): sum over pairings -> list of factor tuples, scalar."""
    out = []
    for m in _matchings(list(range(len(items)))):
        facs, sc = [], sp.Integer(1)
        for i, j in m:
            a, b = items[i], items[j]
            if a == "P" and b == "P":
                sc *= PP
            elif a == "P":
                facs.append(("p", b))
            elif b == "P":
                facs.append(("p", a))
            else:
                facs.append(("gh", a, b))
        out.append((facs, sc))
    return out


def fp_term(facs, scal):
    """int [facs * scal] / (D1 D2) by Feynman parameters, covariant: returns {canon factors: coefficient * MB}."""
    lv = [f[1] for f in facs if f[0] == "l"]
    rest = [f for f in facs if f[0] != "l"]
    ksym = {a: sp.Symbol(f"k[{a}]") for a in lv}
    psy = {a: sp.Symbol(f"pp[{a}]") for a in lv}
    expr = sp.Mul(*[ksym[a] + _X * psy[a] for a in lv]) * scal.xreplace(
        {LL: _K2 + 2 * _X * _KP + _X ** 2 * PP, LP: _KP + _X * PP})
    expr = sp.expand(expr)
    gens = list(ksym.values()) + list(psy.values()) + [_K2, _KP, _X]
    out = {}
    for mon, cf in sp.Poly(expr, *gens).terms():
        nk = len(ksym)
        kl = [a for (a, e) in zip(ksym, mon[:nk]) for _ in range(e)]
        pl = [("p", a) for (a, e) in zip(psy, mon[nk:2 * nk]) for _ in range(e)]
        e2, ep, ex = mon[2 * nk:]
        items = kl + ["P"] * ep
        if len(items) % 2:
            continue
        nh = len(items) // 2
        den = sp.Mul(*[d + 2 * i for i in range(nh)])
        j = e2 + nh
        rat = IL.fp_ratio(j, ex, 0)
        for pf, sc in _sym_pairings(items):
            key = canon(rest + pl + pf)
            out[key] = sp.expand(out.get(key, 0) + cf * sc * rat / den * MB)
    return out


# ------------------------------------------------------------------------------------------------ C3b PV via frozen dred
def pv_term(facs, scal, tag):
    """int [facs * scal]/(D1 D2) via dred.reduce_tensor (Gram in ghat) on the free l-indices; J from the library."""
    lv = [f[1] for f in facs if f[0] == "l"]
    rest = [f for f in facs if f[0] != "l"]
    a0 = sp.degree(scal, LL)
    b0 = sp.degree(scal, LP)
    pc = sp.expand(scal / (LL ** a0 * LP ** b0))
    rules = dred.Rules()
    out = {}
    if not lv:
        J = IL.J_two_point(a0, b0, f"J_{tag}")
        out[canon(rest)] = sp.expand(pc * J)
        return out
    B, Cs = dred.reduce_tensor(len(lv), True, rules, tag)
    idx = {f"m{i}": a for i, a in enumerate(lv)}
    for bk, ck in zip(B, Cs):
        Jsub = {}
        for s in ck.free_symbols:
            if s.name.startswith(f"J_{tag}["):
                i, j = (int(x) for x in s.name[len(tag) + 3:-1].split(","))
                Jsub[s] = IL.J_two_point(i + a0, j + b0, f"J_{tag}")
        cval = sp.expand(ck.xreplace(Jsub))
        for t in bk["terms"]:
            ff = []
            for f in t:
                if f[0] == "g":
                    ff.append(("gh", idx[f[2]], idx[f[3]]))
                else:
                    ff.append(("p", idx[f[2]]))
            key = canon(rest + ff)
            out[key] = sp.expand(out.get(key, 0) + pc * cval)
    return out


# ------------------------------------------------------------------------------------------------ C4 projection, collect
def project_hat(res):
    """ghat_ab = g4_ab - gt_ab (free indices): expand products."""
    out = {}
    for key, c in res.items():
        hs = [f for f in key if f[0] == "gh"]
        rest = [f for f in key if f[0] != "gh"]
        for choice in itertools.product((0, 1), repeat=len(hs)):
            ff = list(rest)
            sgn = 1
            for h, ch in zip(hs, choice):
                if ch:
                    ff.append(("gt", h[1], h[2]))
                    sgn = -sgn
                else:
                    ff.append(("g4", h[1], h[2]))
            k2 = canon(ff)
            out[k2] = sp.expand(out.get(k2, 0) + sgn * c)
    return {k: v for k, v in out.items() if v != 0}


def evaluate(terms, method, tag="C"):
    tot = {}
    for orb, sc, c in terms:
        for facs in orb:
            r = fp_term(list(facs), sc) if method == "fp" else pv_term(list(facs), sc, tag)
            for k, v in r.items():
                tot[k] = sp.expand(tot.get(k, 0) + c * v)
    tot = {k: v for k, v in tot.items() if v != 0}
    return project_hat(tot)


def by_orbit(res, pairs, norm=1):
    """group canonical monomials into symmetrised structures (orbits); coefficient of MB, p.p powers kept in the
    structure label.  Returns {(orbit, p.p power): A(d)} and a consistency flag (all members equal)."""
    group = sym_group(pairs)
    out, ok = {}, True
    seen = {}
    for k, v in res.items():
        orb = orbit(k, group)
        vv = sp.cancel(sp.expand(norm * v / MB))
        nu, de = sp.fraction(vv)
        e = sp.degree(nu, PP) - sp.degree(de, PP)
        cf = sp.factor(sp.cancel(vv / PP ** e))
        if cf.has(PP) or cf.has(MB):
            ok = False
        key = (orb, e)
        if key in seen:
            if sp.cancel(seen[key] - cf) != 0:
                ok = False
        else:
            seen[key] = cf
    for (orb, e), cf in seen.items():
        if cf != 0:
            out[(orb, e)] = cf
    return out, ok


def label(orb, e):
    rep = sorted(orb)[0]
    s = " ".join(f"{f[0]}_{''.join(f[1:])}" for f in rep)
    return (s + (f" (p.p)^{e}" if e else "")).strip()


def is_evanescent(orb):
    return any(f[0] == "gt" for f in sorted(orb)[0])
