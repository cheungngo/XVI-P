def K_vertex(rules):
    """V_K'ch with the leg order of the rule table, re-indexed to canonical (K', c, h) slots (sign retained)."""
    order = rules["leg_order"]["K_c_h"]
    if tuple(order) == ("K", "c", "h"):
        return F.vertices()["V_K_c_h"]
    X = F.S_psi_parts()["X"][1]
    vt = F.ge_vertex("V_K_c_h[" + ",".join(order) + "]", X, [(f, 0) for f in order], 1, "X^(1) reordered")
    pos = [order.index(x) for x in ("K", "c", "h")]
    T = {}
    for comps, poly in vt.T.items():
        mp = {}
        for new, old in enumerate(pos):
            for r in range(4):
                mp[4 * old + r] = F.SP.var(4 * new + r)
        T[tuple(comps[p] for p in pos)] = poly.subs(mp)
    return F.VT(vt.name, ["K", "c", "h"], vt.phase, T, 1, vt.origin)


def grav_weights(rules):
    if rules["graviton_contraction"] == "independent_components":
        return lambda c, d: 1
    return lambda c, d: F.W_OFF[c] * F.W_OFF[d]          # MUTATION: 16-component sum on independent-comp vertices


def pinv_sparse():
    Pi = F.propagators()["graviton"]["Pinv"]
    return {(i, j): Fr(int(Pi[i, j].p), int(Pi[i, j].q)) for i in range(10) for j in range(10) if Pi[i, j] != 0}


def ghost_num():
    G = F.propagators()["ghost"]["numerator"]
    out = {}
    for i in range(4):
        for j in range(4):
            if G[i, j] != 0:
                v = sp.nsimplify(G[i, j])
                assert v.is_rational, "ghost numerator expected real rational"
                out[(i, j)] = Fr(int(v.p), int(v.q))
    return out


def phase_factor(*vts):
    return I ** sum(v.phase for v in vts)


