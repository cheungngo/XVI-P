def _tensor_pairs():
    return [(m, n) for m in range(4) for n in range(4)]


def dd_tensor(mn, rs):
    e = lambda a, b: F.ETA[a] if a == b else 0  # noqa: E731
    (m, n), (r, s) = mn, rs
    return Fr(e(m, r) * e(n, s) + e(m, s) * e(n, r), 2) - Fr(e(m, n) * e(r, s), 2)


def W2(ints):
    """tensor route: V^T_{..(mn)..} = V_{..(min,max)..}/w ; 16x16 de Donder numerator; compare with generator."""
    V = F.vertices()
    TP = _tensor_pairs()
    idx = lambda mn: F.HIDX[(min(mn), max(mn))]  # noqa: E731
    res = {}
    # D02
    VA = F.vt_route(V["V4_grav"], [(0, 1), (0, -1), (1, 0), (-1, 0)])
    N = {}
    for mn in TP:
        for rs in TP:
            dv = dd_tensor(mn, rs)
            if not dv:
                continue
            c, d = idx(mn), idx(rs)
            for a in range(10):
                for b in range(10):
                    p = VA.get((a, b, c, d))
                    if p is not None:
                        N.setdefault((a, b), F.SP()).iadd(p, dv / (F.W_OFF[c] * F.W_OFF[d]))
    N = {k: v for k, v in N.items() if not v.is_zero()}
    res["D02"] = N == ints["D02"]["N"]
    # D14a
    VA = F.vt_route(V["V3_grav"], [(0, 0), (1, 0), (-1, 0)])
    N = {}
    for mn in TP:
        for rs in TP:
            dv = dd_tensor(mn, rs)
            if not dv:
                continue
            c, d = idx(mn), idx(rs)
            for a in range(10):
                p = VA.get((a, c, d))
                if p is not None:
                    N.setdefault((a,), F.SP()).iadd(p, dv / (F.W_OFF[c] * F.W_OFF[d]))
    N = {k: v for k, v in N.items() if not v.is_zero()}
    res["D14a"] = N == ints["D14a"]["N"]
    # D13 (one graviton propagator)
    base = base_rules()
    VA = F.vt_route(K_vertex(base), [(0, -1), (1, 0), (-1, 1)])
    VB = F.vt_route(V["V_cb_c_h"], [(-1, 0), (0, 1), (1, -1)])
    Gh = ghost_num()
    N = {}
    for (ap, mu, c), pa in VA.items():
        for (rho, nu, d), pb in VB.items():
            gv = Gh.get((mu, rho))
            if not gv:
                continue
            tot = Fr(0)
            for mn in TP:
                if idx(mn) != c:
                    continue
                for rs in TP:
                    if idx(rs) == d:
                        tot += dd_tensor(mn, rs) / (F.W_OFF[c] * F.W_OFF[d])
            if tot:
                N.setdefault((ap, nu), F.SP()).iadd_prod(pa, pb, gv * tot)
    N = {k: v for k, v in N.items() if not v.is_zero()}
    # D13 generator under base rules may differ in sign only if the rule table is mutated (handled by W1)
    res["D13"] = N == ints["D13_base_order"]["N"] if "D13_base_order" in ints else N == ints["D13"]["N"]
    P = F.propagators()["graviton"]
    res["Pinv_equals_deDonder_numerator"] = bool(P["Pinv_equals_deDonder_tensor_at_representatives"])
    res["schur_equals_q2P"] = bool(P["schur_equals_q2P"])
    res["full_h_b_inverse_verified"] = bool(P["full_h_b_inverse_verified"])
    return {"checks": res, "pass": all(res.values()),
            "rule": "independent components h_(mn): vertex = d/dh_(mn) (no 1/w), propagator i (P^{-1})_{ab}/(q^2+i0), "
                    "contraction sum over 10x10; tensor form needs V^T = V/w (w=2 off-diagonal) with the 16x16 "
                    "de Donder numerator"}


