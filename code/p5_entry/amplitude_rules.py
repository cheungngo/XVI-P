def integrand_record(name, r):
    num = {",".join(map(str, k)): v.canonical(LP_NAMES) for k, v in sorted(r["N"].items())}
    body = {"graph": name, "prefactor": str(r["prefactor"]), "denominators": r["denominators"],
            "external": r["external"], "routing": r["routing"], "numerator_variables": "l0..l3, p0..p3 (lower)",
            "external_components": "independent h_(mn) index 0..9 = " + str(F.HC) + "; vector index 0..3",
            "numerator": num}
    sha = hashlib.sha256(json.dumps(body, sort_keys=True, separators=(",", ":")).encode()).hexdigest()
    return body, sha


