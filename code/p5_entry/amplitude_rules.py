def _d0_wave(xi_ids, k1):
    """i-stripped delta_0 h_(mn) = a (k1_m xi_n + k1_n xi_m), xi_n = eta_nn xi^n; k1: list of SP."""
    out = {}
    for a, (m, n) in enumerate(F.HC):
        v = (k1[m] * F.SP.var(xi_ids[n], F.ETA[n])) + (k1[n] * F.SP.var(xi_ids[m], F.ETA[m]))
        out[a] = v.scale(F.A_GH)
    return out


def _d1_wave(xi_ids, k1, e, ke):
    """i-stripped delta_1 h_(mn) = a (xi^r ke_r e_mn + e_rn k1_m xi^r + e_mr k1_n xi^r); e: {comp idx: SP}."""
    def E(r, s):
        return e.get(F.HIDX[(min(r, s), max(r, s))], F.SP())
    out = {}
    for a, (m, n) in enumerate(F.HC):
        v = F.SP()
        for r in range(4):
            x = F.SP.var(xi_ids[r])
            v.iadd(x * ke[r] * E(m, n))
            v.iadd(x * k1[m] * E(r, n))
            v.iadd(x * k1[n] * E(m, r))
        out[a] = v.scale(F.A_GH)
    return out


